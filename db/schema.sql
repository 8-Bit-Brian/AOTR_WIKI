-- Schema verified against the project's MySQL 8 database with SHOW CREATE TABLE units.
CREATE TABLE IF NOT EXISTS `units` (
  `UNIT_ID` int NOT NULL AUTO_INCREMENT,
  `NAME` varchar(200) DEFAULT NULL,
  `COST` int DEFAULT NULL,
  `COMMAND_POINTS` int DEFAULT NULL,
  `BOUNTY_VAL` int DEFAULT NULL,
  `BUILD_TIME` int DEFAULT NULL,
  `HP` int DEFAULT NULL,
  `ARMORSET` varchar(100) DEFAULT NULL,
  `WEAPONSET` text,
  `HORDESPEED` int DEFAULT NULL,
  `SPECIAL` text,
  `EXPERIENCE` varchar(100) DEFAULT NULL,
  `FACTION_ID` int NOT NULL,
  PRIMARY KEY (`UNIT_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
